def column_aggregates(series: pd.Series) -> dict[str, float]:
    s = series.astype(float)
    q = s.quantile([0.01, 0.05, 0.95, 0.99])
    return {
        "sum": float(s.sum()),
        "median": float(s.median()),
        "mean": float(s.mean()),
        "min": float(s.min()),
        "max": float(s.max()),
        "std": float(s.std(ddof=0)),
        "sumsq": float((s * s).sum()),
        "p1": float(q.loc[0.01]),
        "p5": float(q.loc[0.05]),
        "p95": float(q.loc[0.95]),
        "p99": float(q.loc[0.99]),
    }


def band_outlier_counts(df: pd.DataFrame) -> dict[str, int]:
    out: dict[str, int] = {}
    for col, band in PLAUSIBILITY_BANDS.items():
        if col not in df.columns:
            continue
        s = df[col].astype(float)
        out[col] = int(((s < band.low) | (s > band.high)).sum())
    return out


def fits_column_reference(df: pd.DataFrame) -> dict[str, Any]:
    return {
        "n": int(len(df)),
        "columns": {col: column_aggregates(df[col]) for col in CHECK_COLUMNS if col in df.columns},
    }


def stat_close(got: float, ref: float, abs_tol: float) -> bool:
    scale = max(abs(ref), 1e-30)
    return abs(got - ref) <= abs_tol + AGGREGATE_REL_TOL * scale


def verify_fits_aggregates(
    df: pd.DataFrame,
    ref: dict[str, Any],
    band_counts_ref: dict[str, int],
    n_expected: int,
) -> list[str]:
    errors: list[str] = []
    if len(df) != n_expected:
        errors.append(f"fits rows: got {len(df)} cert {n_expected}")
    counts = band_outlier_counts(df)
    for col, want in band_counts_ref.items():
        if counts.get(col, -1) != int(want):
            errors.append(f"fits band outliers {col}: got {counts.get(col)} cert {want}")
    for col in CHECK_COLUMNS:
        if col not in df.columns:
            errors.append(f"fits.csv missing column {col}")
            continue
        got = column_aggregates(df[col])
        want = ref["columns"][col]
        for stat in AGG_STATS:
            tol = aggregate_abs_tolerance(col, stat)
            if not stat_close(got[stat], float(want[stat]), tol):
                errors.append(f"fits.{col}.{stat}: got {got[stat]} cert {want[stat]} tol {tol}")
    return errors


def apply_run_41746542087_reproductions(df: pd.DataFrame, mode: str) -> pd.DataFrame:
    """grk-proof's three ways to spread a −CALIBRATION_FC_SUM_DRIFT_KHZ shift on fc sum."""
    delta = -CALIBRATION_FC_SUM_DRIFT_KHZ
    if mode == "uniform":
        return uniform_fc_sum_drift(df, delta)
    if mode == "median_row":
        row = int(df["fc_khz"].sub(df["fc_khz"].median()).abs().idxmin())
        return single_row_fc_sum_drift(df, row, delta)
    if mode == "max_cm_row":
        row = int(df["cm_nf"].idxmax())
        return single_row_fc_sum_drift(df, row, delta)
    raise ValueError(mode)


def uniform_fc_sum_drift(df: pd.DataFrame, delta_sum_khz: float) -> pd.DataFrame:
    out = df.copy()
    out["fc_khz"] = (out["fc_khz"] + delta_sum_khz / len(out)).clip(1.0, 1000.0)
    return recompute_cm_nf(out)


def single_row_fc_sum_drift(df: pd.DataFrame, row: int, delta_sum_khz: float) -> pd.DataFrame:
    out = df.copy()
    out.loc[row, "fc_khz"] = float(np.clip(out.loc[row, "fc_khz"] + delta_sum_khz, 1.0, 1000.0))
    return recompute_cm_nf(out)


def gaussian_fc_noise(df: pd.DataFrame, sigma_khz: float, seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    out = df.copy()
    out["fc_khz"] = (out["fc_khz"] + rng.normal(0.0, sigma_khz, len(out))).clip(1.0, 1000.0)
    return recompute_cm_nf(out)


def smallest_detectable_fc_shift_khz(
    df: pd.DataFrame,
    ref: dict[str, Any],
    band_counts_ref: dict[str, int],
    n_expected: int,
    *,
    row_index: int,
    delta_low: float = 0.0,
    delta_high: float = 200.0,
) -> float:
    base = df.copy()
    if verify_fits_aggregates(base, ref, band_counts_ref, n_expected):
        raise ValueError("baseline fits do not match reference")

    def fails(delta: float) -> bool:
        trial = base.copy()
        trial.loc[row_index, "fc_khz"] = float(trial.loc[row_index, "fc_khz"]) + delta
        trial = recompute_cm_nf(trial)
        return bool(verify_fits_aggregates(trial, ref, band_counts_ref, n_expected))

    if not fails(delta_high):
        return float("inf")
    lo, hi = delta_low, delta_high
    for _ in range(50):
        mid = (lo + hi) / 2
        if fails(mid):
            hi = mid
        else:
            lo = mid
    return hi


def row_near_fc_quantile(df: pd.DataFrame, target: str) -> int:
    if target == "median":
        return int(df["fc_khz"].sub(df["fc_khz"].median()).abs().idxmin())
    if target == "mean":
        return int(df["fc_khz"].sub(df["fc_khz"].mean()).abs().idxmin())
    raise ValueError(target)
